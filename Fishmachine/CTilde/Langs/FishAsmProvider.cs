		public FishAsmProvider(FishCompileState State)
		{
			this.State = State;

			EmitRaw("# Generated by C~");
			EmitRaw("# Labels generate in the bytecode bin as the show up in the code, adjecent labels share address by design");
			EmitRaw("# int_table address is set by the VM when the program runs");
			EmitRaw("# All global variables except functions are supposed to be stored using double indirection");
			EmitRaw("# Assignment to global variables which are arrays, strings or pointer types should change the address of the variable");
			EmitRaw("# Assignment to non-pointer global variables should assign their value, not their address.");
			EmitRaw("# Dereference of non-pointer globals should return their value");
			EmitRaw("# Dereference of pointer and string globals should return their reference");

